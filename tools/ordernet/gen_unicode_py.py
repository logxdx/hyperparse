"""Generate src/ordernet/unicode_py.inc: the Python str character classes the OrderNet
port needs, as sorted inclusive code point ranges, taken from Python itself by walking
every code point (run with the Python the reference ran with: its unicodedata version
decides the tables).

    python tools/ordernet/gen_unicode_py.py src/ordernet/unicode_py.inc
"""

import sys
import unicodedata

PROPS = [
    ("kSpace", "str.isspace (str.strip(), re \\s)", lambda c: c.isspace()),
    ("kDigit", "str.isdigit", lambda c: c.isdigit()),
    ("kDecimal", "str.isdecimal (re \\d)", lambda c: c.isdecimal()),
    ("kAlpha", "str.isalpha", lambda c: c.isalpha()),
    ("kUpper", "str.isupper of one character", lambda c: c.isupper()),
    ("kLower", "str.islower of one character", lambda c: c.islower()),
    ("kWide", 'unicodedata.east_asian_width in "WF"', lambda c: unicodedata.east_asian_width(c) in "WF"),
]


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        hit = pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    lines = [
        f"// Generated by tools/ordernet/gen_unicode_py.py from Python {sys.version.split()[0]}",
        f"// (unicodedata {unicodedata.unidata_version}). Do not edit by hand.",
        "// Inclusive code point ranges, sorted; included by src/ordernet/text.cpp.",
    ]
    for name, what, pred in PROPS:
        rs = ranges(pred)
        lines.append(f"// {what}: {len(rs)} ranges")
        lines.append(f"inline constexpr Range {name}[] = {{")
        row = []
        for lo, hi in rs:
            row.append(f"{{0x{lo:X}, 0x{hi:X}}},")
            if len(row) == 6:
                lines.append("    " + " ".join(row))
                row = []
        if row:
            lines.append("    " + " ".join(row))
        lines.append("};")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
